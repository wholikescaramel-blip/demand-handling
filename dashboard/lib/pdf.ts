import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from "pdf-lib";

export type PoDoc = {
  po_number: string;
  created_at: string; // ISO
  vendor_name: string | null;
  vendor_key: string;
  run_ids: string | null;
  created_by: string | null;
  total_qty: number;
  lines: { sku: string; name: string | null; qty: number; run_id: string }[];
};

/** The built-in PDF fonts only cover Latin-1, so map the usual typographic characters and drop the rest. */
export function pdfText(s: string): string {
  return s
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/[–—]/g, "-")
    .replace(/·|•/g, "-")
    .replace(/₹/g, "Rs ")
    .replace(/…/g, "...")
    .replace(/[^\x20-\x7E\xA0-\xFF]/g, "");
}

const fmtDate = (iso: string) =>
  new Intl.DateTimeFormat("en-IN", { day: "2-digit", month: "short", year: "numeric", timeZone: "Asia/Kolkata" }).format(new Date(iso));

const INK = rgb(0.08, 0.13, 0.24);
const MUTED = rgb(0.4, 0.44, 0.52);
const LINE = rgb(0.85, 0.87, 0.92);

/**
 * One-page-per-30-lines purchase order. There are no prices in the data, so the document states quantities only and
 * leaves rate and delivery date for the vendor to confirm.
 */
export async function buildPoPdf(po: PoDoc, opts: { company?: string; shipTo?: string } = {}): Promise<Uint8Array> {
  const company = opts.company ?? "Freshroots";
  const shipTo = opts.shipTo ?? "Pune Central Warehouse, Pune";
  const doc = await PDFDocument.create();
  doc.setTitle(`Purchase order ${po.po_number}`);
  doc.setProducer("Demand Planning Desk");
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);

  const W = 595, H = 842, M = 48;
  const cols = { n: M, sku: M + 30, item: M + 120, qty: W - M - 60 };
  let page!: PDFPage;
  let y = 0;

  const text = (p: PDFPage, s: string, x: number, yy: number, size = 10, f: PDFFont = font, color = INK, align: "l" | "r" = "l") => {
    const t = pdfText(s);
    const w = f.widthOfTextAtSize(t, size);
    p.drawText(t, { x: align === "r" ? x - w : x, y: yy, size, font: f, color });
  };
  const fit = (s: string, size: number, maxW: number) => {
    let t = pdfText(s);
    while (t.length > 1 && font.widthOfTextAtSize(t, size) > maxW) t = t.slice(0, -2);
    return t === pdfText(s) ? t : t.trimEnd() + "...";
  };
  const tableHeader = () => {
    page.drawRectangle({ x: M, y: y - 6, width: W - 2 * M, height: 22, color: INK });
    const white = rgb(1, 1, 1);
    text(page, "#", cols.n + 6, y, 9, bold, white);
    text(page, "SKU", cols.sku, y, 9, bold, white);
    text(page, "Item", cols.item, y, 9, bold, white);
    text(page, "Qty", cols.qty + 54, y, 9, bold, white, "r");
    y -= 26;
  };
  const newPage = () => {
    page = doc.addPage([W, H]);
    y = H - M;
  };

  newPage();
  text(page, company.toUpperCase(), M, y, 11, bold, MUTED);
  text(page, "PURCHASE ORDER", M, y - 26, 22, bold);
  text(page, po.po_number, W - M, y - 2, 14, bold, INK, "r");
  text(page, `Date: ${fmtDate(po.created_at)}`, W - M, y - 20, 10, font, MUTED, "r");
  y -= 60;
  page.drawLine({ start: { x: M, y }, end: { x: W - M, y }, thickness: 1, color: LINE });
  y -= 22;

  const block = (label: string, lines: string[], x: number) => {
    text(page, label, x, y, 8, bold, MUTED);
    lines.forEach((l, i) => text(page, l, x, y - 14 - i * 13, 10));
  };
  block("TO (VENDOR)", [po.vendor_name ?? po.vendor_key, `Vendor code: ${po.vendor_key}`], M);
  block("SHIP TO", [company, shipTo], 320);
  y -= 58;
  block("REFERENCE", [`Planning run: ${po.run_ids ?? "n/a"}`], M);
  block("APPROVED BY", [po.created_by ?? "n/a"], 320);
  y -= 46;

  tableHeader();
  po.lines.forEach((l, i) => {
    if (y < 120) {
      newPage();
      tableHeader();
    }
    if (i % 2 === 1) page.drawRectangle({ x: M, y: y - 6, width: W - 2 * M, height: 20, color: rgb(0.97, 0.97, 0.99) });
    text(page, String(i + 1), cols.n + 6, y, 10);
    text(page, l.sku, cols.sku, y, 10, bold);
    text(page, fit(l.name ?? "", 10, cols.qty - cols.item - 12), cols.item, y, 10);
    text(page, String(l.qty), cols.qty + 54, y, 10, bold, INK, "r");
    y -= 22;
  });

  page.drawLine({ start: { x: M, y: y + 8 }, end: { x: W - M, y: y + 8 }, thickness: 1, color: LINE });
  y -= 10;
  text(page, "Total units", cols.qty - 10, y, 10, bold, INK, "r");
  text(page, String(po.total_qty), cols.qty + 54, y, 11, bold, INK, "r");
  y -= 40;

  if (y < 110) {
    newPage();
  }
  text(page, "Notes", M, y, 9, bold, MUTED);
  text(page, "Unit rates and the delivery date are to be confirmed by the vendor when accepting this order.", M, y - 14, 9, font, MUTED);
  text(page, "Please quote the PO number on all delivery notes and invoices.", M, y - 27, 9, font, MUTED);

  doc.getPages().forEach((p, i, all) => {
    text(p, `Generated by Demand Planning Desk after approval. Page ${i + 1} of ${all.length}`, M, 28, 8, font, MUTED);
  });
  return doc.save();
}
